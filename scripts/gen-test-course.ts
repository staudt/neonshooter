// Generates maps/test_course.map: a movement test course with known dimensions, used by the
// headless movement sim tests and as a starting map. Writes Valve 220 format (TrenchBroom-editable).
// Run: node scripts/gen-test-course.ts   (overwrites the file — make hand edits in a copy)
// Authoring units are METERS, Y-up (see scripts/mapgen.ts). Player starts at the origin facing -Z.
import { MapBuilder } from './mapgen.ts';
import type { V3 } from './mapgen.ts';

const m = new MapBuilder();

// ---------------------------------------------------------------------------
// Layout: lanes running along -Z, separated along X. Floor top at y = 0.

const FLOOR_MIN: V3 = [-40, -1, -90];
const FLOOR_MAX: V3 = [40, 0, 10];
m.box(FLOOR_MIN, FLOOR_MAX, 'concrete_dark', 'concrete_floor');
// Perimeter walls (4 m tall) with a neon trim line.
m.box([-41, -1, -91], [-40, 4, 11]);
m.box([40, -1, -91], [41, 4, 11]);
m.box([-41, -1, -91], [41, 4, -90]);
m.box([-41, -1, 10], [41, 4, 11]);
m.box([-40, 3.6, -90], [-39.9, 3.7, 10], 'neon_cyan');
m.box([39.9, 3.6, -90], [40, 3.7, 10], 'neon_cyan');

// Lane A (x -36..-30): stairs. 12 steps of 0.25 m rise, 0.35 m run, up to a 3 m landing.
for (let i = 0; i < 12; i++) {
  const z = -6 - i * 0.35;
  m.box([-36, 0, z - 0.35], [-30, (i + 1) * 0.25, z], 'concrete', 'concrete_floor');
}
m.box([-36, 0, -16.2], [-30, 3, -10.2], 'concrete', 'concrete_floor');
// Steps that are too tall to step (0.6 m) — must jump/mantle.
m.box([-36, 0, -24], [-30, 0.6, -20], 'concrete', 'concrete_floor');

// Lane B (x -26..-20): ramps of 20°, 35°, 50° (last should be too steep to walk).
const rampLen = 6;
for (const [i, deg] of [20, 35, 50].entries()) {
  const z0 = -6 - i * 14;
  const h = Math.tan((deg * Math.PI) / 180) * rampLen;
  m.ramp(-26, -20, 0, z0, z0 - rampLen, h);
  m.box([-26, 0, z0 - rampLen - 3], [-20, h, z0 - rampLen], 'concrete', 'concrete_floor');
}

// Lane C (x -16..-10): mantle ledges 1.0, 1.4, 2.0 m, and an un-mantleable 3.2 m wall.
for (const [i, h] of [1.0, 1.4, 2.0, 3.2].entries()) {
  const z = -8 - i * 10;
  m.box([-16, 0, z - 4], [-10, h, z], 'concrete', 'concrete_floor');
  m.box([-16, h - 0.08, z - 0.06], [-10, h, z], 'neon_orange'); // ledge lip marker
}

// Lane D (x -6..6): long sprint/slide corridor with a low tunnel (1.2 m clearance: crouch/slide only) and a slide hill.
m.box([-6, 1.2, -30], [6, 3, -24]); // tunnel roof
m.box([-6, 1.15, -30], [6, 1.2, -29.9], 'neon_magenta');
m.ramp(-6, 6, 0, -40, -46, 2); // up
m.box([-6, 0, -50], [6, 2, -46], 'concrete', 'concrete_floor');
// downhill (rises toward +Z): build as a ramp facing the other way
m.convex(
  [
    [-6, 0, -58],
    [6, 0, -58],
    [-6, 0, -50],
    [6, 0, -50],
    [-6, 2, -50],
    [6, 2, -50],
  ],
  [
    [0, 1, 3],
    [2, 3, 5],
    [0, 1, 5],
    [0, 2, 4],
    [1, 3, 5],
  ],
  'concrete_floor',
);

// Lane E (x 10..16): jump gaps 2, 3, 4, 5 m between 1 m platforms.
let z = -6;
for (const gap of [2, 3, 4, 5]) {
  m.box([10, 0, z - 4], [16, 1, z], 'concrete', 'concrete_floor');
  z -= 4 + gap;
}
m.box([10, 0, z - 4], [16, 1, z], 'concrete', 'concrete_floor');

// Lane F (x 20..38): cover arena — pillars, crates, a 2-storey tower with a ramp.
for (const [x, zz] of [
  [23, -10],
  [29, -14],
  [35, -10],
  [23, -22],
  [35, -22],
] as [number, number][]) {
  m.box([x - 0.6, 0, zz - 0.6], [x + 0.6, 4, zz + 0.6]);
  m.box([x - 0.6, 3.2, zz + 0.6], [x + 0.6, 3.3, zz + 0.62], 'neon_cyan');
}
for (const [x, zz, h] of [
  [26, -18, 1.1],
  [32, -18, 1.1],
  [29, -26, 0.8],
] as V3[])
  m.box([x - 1, 0, zz - 1], [x + 1, h, zz + 1], 'metal');
m.box([22, 0, -44], [36, 4, -34], 'concrete', 'concrete_floor'); // tower base (roof at 4 m)
m.ramp(20, 22, 0, -30, -40, 4); // narrow ramp up the side
m.box([20, 0, -44], [22, 4, -40], 'concrete', 'concrete_floor');

// Clip brush: invisible wall test (should block the player, not render).
m.box([-6, 0, -70], [6, 3, -69.8], 'clip');

// ---------------------------------------------------------------------------
m.point('info_player_start', [0, 0.01, 0], { angle: 90 }); // angle 90 = -Z in game space
// Shooting range in lane F: dummies at increasing distances from the spawn, one on the tower.
for (const pos of [
  [26, 0, -30],
  [33, 0, -31],
  [24, 0, -55],
  [30, 0, -64],
  [35, 0, -78],
  [29, 4, -38],
] as V3[])
  m.point('target_dummy', pos, { angle: 270 });
m.point('light_point', [0, 3, -27], { _color: '1 0.3 0.9', intensity: 15, range: 10 });
m.point('light_point', [29, 3.5, -18], { _color: '0.4 0.9 1', intensity: 25, range: 14 });

m.write(
  'maps/test_course.map',
  'Generated by scripts/gen-test-course.ts — movement test course (dimensions are asserted by tests).',
);
